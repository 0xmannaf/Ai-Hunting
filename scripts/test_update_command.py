#!/usr/bin/env python3
"""Tests for the /update command (.opencode/commands/update.md) — end to end.

The /update command sequence is:
  1. registry check            python scripts/skill_registry.py check
  2. generate runtime copies   python scripts/skill_registry.py generate
  3. pipeline                  bash scripts/update.sh  (fetch->process->index->learn)
  4. full test pass            python -m pytest scripts/ -v

These tests verify that exact sequence offline: command file contract, registry
integrity, pipeline artifacts, briefing regeneration, and idempotency. No
network, no live targets.
"""

import json
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from scripts import skill_registry as sr  # noqa: E402
from scripts.update_steps import (  # noqa: E402
    BRIEFING_PATH, INDEX_PATH, LESSONS_PATH,
    step_fetch, step_index, step_learn, step_process, run_all,
)

UPDATE_COMMAND = ROOT / ".opencode/commands/update.md"


class TestUpdateCommandContract(unittest.TestCase):
    def test_command_file_exists_and_registered(self):
        self.assertTrue(UPDATE_COMMAND.exists(), ".opencode/commands/update.md missing")
        text = UPDATE_COMMAND.read_text(encoding="utf-8")
        self.assertIn("description:", text)
        self.assertIn("agent: build", text)
        self.assertNotIn("id: update", text)
        self.assertIn("$ARGUMENTS", text)

    def test_command_references_existing_scripts(self):
        text = UPDATE_COMMAND.read_text(encoding="utf-8")
        for ref in ("scripts/skill_registry.py", "scripts/runtime_preflight.py",
                    "scripts/update.sh",
                    "learning_engine/scripts/audit_learning_engine.py"):
            self.assertIn(ref, text, f"command does not reference {ref}")
            self.assertTrue((ROOT / ref).exists(), f"referenced script missing: {ref}")
        for t in ("test_skill_registry.py", "test_runtime_contract.py",
                  "test_learning_engine.py", "test_update_pipeline.py",
                  "test_update_command.py"):
            self.assertTrue((ROOT / "scripts" / t).exists(), f"test file missing: {t}")


class TestUpdateCommandSequence(unittest.TestCase):
    """Runs the /update sequence on isolated temporary workspaces."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp(prefix="update_cmd_"))
        cls.registry = sr._load_registry()

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.tmp, ignore_errors=True)

    @classmethod
    def _fresh_ws(cls) -> Path:
        """A fresh workspace: sample feed + metadata + memory templates + briefing."""
        ws = cls.tmp / f"ws-{len(list(cls.tmp.iterdir()))}"
        for p in ("writeups/raw", "writeups/processed", "writeups/metadata",
                  "writeups/feeds/sample", "memory"):
            (ws / p).mkdir(parents=True, exist_ok=True)
        (ws / "writeups/feeds/sample/sample-one.md").write_text(
            "---\ntitle: \"Sample SSRF via PDF fetch\"\nsource: \"sample corpus\"\n"
            "date: 2026-05-01\ntags: [ssrf]\n---\n\nBody.\n", encoding="utf-8")
        (ws / "writeups/metadata/f-update-0001.json").write_text(
            json.dumps({"finding_id": "f-update-0001", "target": "test.example.com",
                        "vuln_class": "ssrf", "title": "Sample SSRF via PDF fetch",
                        "severity": "high", "confidence": 0.9, "verdict": "CONFIRMED",
                        "signals": {"ssrf_metadata": True}}), encoding="utf-8")
        (ws / "writeups/metadata/f-update-0002.json").write_text(
            json.dumps({"finding_id": "f-update-0002", "target": "test.example.com",
                        "vuln_class": "ssrf", "title": "Second SSRF via redirect",
                        "severity": "high", "confidence": 0.85, "verdict": "CONFIRMED",
                        "signals": {"ssrf_metadata": True}}), encoding="utf-8")
        (ws / LESSONS_PATH).write_text("# Report Lessons (distilled)\n\n> stale\n",
                                       encoding="utf-8")
        (ws / "memory/patterns.md").write_text(
            "# Patterns\n\n## Patterns\n\n_(none)_\n", encoding="utf-8")
        (ws / "memory/methodology.md").write_text(
            "# Methodology\n\n## 1. Prep\n", encoding="utf-8")
        (ws / BRIEFING_PATH).write_text(
            "# Agent Briefing - Bug Bounty Session Start\n\n"
            "- **Last updated:** 1970-01-01\n"
            "- **Knowledge base:** 0 processed write-ups\n"
            "- **Role:** test\n\n"
            "## 3. Knowledge State (Current Learned Biases)\n\n"
            "_(Regenerated by /update — learned biases from report-lessons.md + patterns.md)_\n"
            "1. stale bias\n\n## 4. Next Section\n", encoding="utf-8")
        return ws

    # Step 1 of /update: registry check.
    def test_step1_registry_check_passes(self):
        self.assertEqual(sr.check(self.registry), [])

    # Step 2 of /update: generate runtime copies (no drift).
    def test_step2_generate_writes_runtime_copies(self):
        written = sr.generate(self.registry)
        self.assertEqual(len(written), len(self.registry["skills"]))
        self.assertEqual(sr.check(self.registry), [])

    # Step 3 of /update: fetch -> process -> index -> learn (offline).
    def test_step3_pipeline_produces_all_artifacts(self):
        ws = self._fresh_ws()
        results = run_all(ws, offline=True)
        self.assertEqual(results["fetch"]["copied"], 1)
        self.assertEqual(results["process"]["written"], 1)
        self.assertEqual(results["index"]["indexed"], 1)
        self.assertEqual(results["learn"]["ingested"], 2)

        index = (ws / INDEX_PATH).read_text(encoding="utf-8")
        self.assertIn("Knowledge base:** 1 processed write-ups", index)
        lessons = (ws / LESSONS_PATH).read_text(encoding="utf-8")
        self.assertIn("ssrf", lessons)
        briefing = (ws / BRIEFING_PATH).read_text(encoding="utf-8")
        self.assertNotIn("1970-01-01", briefing)
        self.assertIn("1 processed write-ups", briefing)
        self.assertIn("ssrf", briefing)

    # Step 4 of /update: the suite these tests belong to must stay green.
    def test_step4_suite_files_present(self):
        for t in ("test_skill_registry.py", "test_runtime_contract.py",
                  "test_learning_engine.py", "test_update_pipeline.py",
                  "test_update_command.py"):
            self.assertTrue((ROOT / "scripts" / t).exists(), f"missing {t}")

    # The whole /update sequence is idempotent and safe to re-run.
    def test_rerun_is_idempotent(self):
        ws = self._fresh_ws()
        run_all(ws, offline=True)
        before = (ws / BRIEFING_PATH).read_text(encoding="utf-8")
        results = run_all(ws, offline=True)
        self.assertEqual(results["fetch"]["copied"], 0)
        self.assertEqual(results["process"]["written"], 0)
        self.assertEqual(results["learn"]["ingested"], 0)
        after = (ws / BRIEFING_PATH).read_text(encoding="utf-8")
        self.assertEqual(before, after)
        self.assertEqual(sr.check(self.registry), [])


if __name__ == "__main__":
    unittest.main(verbosity=2)